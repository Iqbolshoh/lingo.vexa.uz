#!/usr/bin/env python3
"""Wrap Uzbek UI strings in t() and generate src/lang/en.php.

Usage: python3 -I tools/i18n/i18n_build.py .   (from the project root)
Translation tables live in tr_*.py next to this script: each defines
FILES = {relpath: [(uz, en), ...]} and optionally SHARED = [(uz, en), ...]
(dictionary-only entries for strings built in PHP code).
"""
import glob
import importlib.util
import os
import re
import sys

root = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))

files, shared = {}, []
for path in sorted(glob.glob(os.path.join(here, 'tr_*.py'))):
    spec = importlib.util.spec_from_file_location(os.path.basename(path)[:-3], path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    for rel, pairs in getattr(mod, 'FILES', {}).items():
        files.setdefault(rel, []).extend(pairs)
    shared.extend(getattr(mod, 'SHARED', []))


def php_quote(s: str) -> str:
    return s.replace('\\', '\\\\').replace("'", "\\'")


problems = 0
for rel, pairs in files.items():
    path = os.path.join(root, rel)
    src = open(path, encoding='utf-8').read()
    for uz, _en in sorted(pairs, key=lambda p: -len(p[0])):
        q = php_quote(uz)
        n = 0
        # 1) PHP string literal 'uz' -> t('uz')
        lit = re.compile(r"(?<!t\()'" + re.escape(q) + r"'")
        src, k = lit.subn("t('" + q.replace('\\', '\\\\') + "')", src)
        n += k
        # 2) HTML text node / attribute value -> <?= t('uz') ?>
        html = re.compile(r"(?<=[>\s\"])(?<!t\(')" + re.escape(uz) + r"(?=\s*[<\"])")
        src, k = html.subn(lambda m: "<?= t('" + q + "') ?>", src)
        n += k
        already = src.count("t('" + q + "')")
        if n == 0 and already == 0:
            print(f'NOT FOUND [{rel}]: {uz[:90]}')
            problems += 1
    open(path, 'w', encoding='utf-8').write(src)

entries = {}
for pairs in list(files.values()) + [shared]:
    for uz, en in pairs:
        if uz in entries and entries[uz] != en:
            print(f'CONFLICT: {uz[:60]}')
        entries[uz] = en

os.makedirs(os.path.join(root, 'src/lang'), exist_ok=True)
with open(os.path.join(root, 'src/lang/en.php'), 'w', encoding='utf-8') as f:
    f.write("<?php\n\ndeclare(strict_types=1);\n\n// English UI strings keyed by the Uzbek source text. Generated by tools/i18n_build.py.\n\nreturn [\n")
    for uz, en in entries.items():
        f.write(f"    '{php_quote(uz)}' => '{php_quote(en)}',\n")
    f.write("];\n")

print(f'{len(entries)} entries, {problems} problems')
